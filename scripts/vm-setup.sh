#!/usr/bin/env bash
# One-time setup of a fresh Ubuntu VM (e.g. Oracle Always Free ARM): installs Docker and writes .env
# with a random database password and the Cloudflare tunnel token. Run it from the project folder.
set -euo pipefail
cd "$(dirname "$0")/.."

if ! command -v docker >/dev/null 2>&1; then
  curl -fsSL https://get.docker.com | sudo sh
  sudo usermod -aG docker "$USER"
  echo
  echo "Docker is installed. Log out and back in (type: exit, then ssh again), then run this script again."
  exit 0
fi
if ! docker info >/dev/null 2>&1; then
  echo "Docker is installed but this user cannot use it yet: log out and back in, then run this script again."
  exit 1
fi

if [ ! -f .env ]; then
  cp .env.example .env
  printf '\n# generated by scripts/vm-setup.sh\nPOSTGRES_PASSWORD=%s\n' "$(openssl rand -hex 16)" >> .env
  echo "Created .env with a random database password."
fi
if ! grep -q '^TUNNEL_TOKEN=.' .env; then
  read -rsp "Cloudflare tunnel token (the long text starting with eyJ): " token
  echo
  [ -n "$token" ] || { echo "No token given."; exit 1; }
  printf 'TUNNEL_TOKEN=%s\n' "$token" >> .env
fi
chmod 600 .env

echo
echo "Ready. Next:"
echo "  - to bring your data over: scripts/db-restore.sh nexus-backup.sql"
echo "  - then start everything:   docker compose --profile tunnel up -d --build"
